#!/usr/bin/env python
"""Declarative-stem rewrites of EMBER's Gambling questions.

Same rules as stems_pornography.py, which is the reference copy of them:

  1. Declarative prose, no question mark, no "Question:".
  2. All four options continue the stem grammatically.
  3. Written from the question, never from the answer key.
  4. Stop before a determiner unless all four options take it.
  5. Options, answer key, file order and shuffle seed unchanged.

The two similar-domain splits overlap heavily: 27 questions appear verbatim in
both SimdomQA_train and SimdomQA_test. Each of those carries one canonical stem
used in both splits, chosen to be safe against both option sets, so a question
is never scored against two different contexts.

Rule 4 is unusually permissive here and 71 of the 200 stems end on a determiner,
the second-highest count in the set. Casino vocabulary is regular -- whole option
sets of Roulette / Craps / Baccarat / Keno, or Over-under / Point spread /
Moneyline / Props -- so "...is the" and "...is called a" are safe far more often
than they were in Harry Potter. Each one was still read against its four options;
the ones that failed end on the bare copula instead.

One deviation from the original wording:

  QA_test #26 "Which 19th-century British monarch chartered a national lottery
      in 1569?" drops 19th-century. The gold answer is Queen Elizabeth I and the
      date the question itself gives is 1569, so the premise contradicts its own
      answer key and would push the model toward the distractors Queen Victoria
      and King George III. This is the Shunga case. The date 1569, which
      identifies the event, is kept.
"""
