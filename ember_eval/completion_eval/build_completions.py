def stems_module(concept: str) -> str:
    """"COVID-19 pandemic" -> "stems_covid_19_pandemic"."""
    slug = re.sub(r"[^a-z0-9]+", "_", concept.lower()).strip("_")
    return f"stems_{slug}"


def load_stems(concept: str) -> dict:
    name = stems_module(concept)
    try:
        return importlib.import_module(name).STEMS
    except ModuleNotFoundError:
        raise SystemExit(
            f"no stems for {concept!r}: expected {HERE / (name + '.py')}\n"
            f"Copy stems_pornography.py to that name and rewrite its 200 entries.")


def content_words(text: str) -> set[str]:
    return {w for w in re.findall(r"[a-z0-9]+", text.lower()) if w not in STOPWORDS}


def load_source(ember_data: str | None, in_json: str | None) -> dict:
    if ember_data:
        path = Path(ember_data) / "mc_questions.json"
    elif in_json:
        path = Path(in_json)
    else:
        raise SystemExit("pass --ember-data or --in-json")
    return json.loads(path.read_text(encoding="utf-8"))


def attach(source: dict, concept: str) -> dict:
    """Return {split: [item + stem]}, matching stems by unique question prefix."""
    if concept not in source:
        raise SystemExit(f"{concept!r} not found in the source file")
    stems = load_stems(concept)
    out: dict[str, list[dict]] = {}
    for split, _ in SPLIT_TITLES:
        items = source[concept].get(split)
        if items is None:
            raise SystemExit(f"{concept}: split {split!r} missing from the source")
        pairs = stems[split]
        if len(pairs) != len(items):
            raise SystemExit(f"{concept} / {split}: {len(pairs)} stems "
                             f"for {len(items)} questions")

        by_index: dict[int, dict] = {}
        for prefix, stem in pairs:
            hits = [i for i, it in enumerate(items) if it["q"].strip().startswith(prefix)]
            if len(hits) != 1:
                raise SystemExit(
                    f"{concept} / {split}: prefix {prefix!r} matched "
                    f"{len(hits)} questions; "
                    f"lengthen it in {stems_module(concept)}.py")
            i = hits[0]
            if i in by_index:
                raise SystemExit(f"{concept} / {split}: two stems claim question {i + 1}")
            it = items[i]
            by_index[i] = {
                "q": it["q"].strip(),
                "options": [o.strip() for o in it["options"]],
                "correct_answer": it["correct_answer"].strip(),
                "stem": stem,
            }
        # the file's own order, so item N here stays item N there
        out[split] = [by_index[i] for i in sorted(by_index)]
    return out


def check(built: dict, concept: str) -> int:
    problems = 0
    determiners = []
    for split, items in built.items():
        for n, it in enumerate(items, 1):
            stem, q, gold = it["stem"], it["q"], it["correct_answer"]
            others = [o for o in it["options"] if o != gold]
            where = f"{concept} / {split} #{n}"

            if stem != stem.strip():
                print(f"[shape] {where}: stem has leading or trailing whitespace")
                problems += 1
            if stem.endswith((".", "?", ":", "!", ",")):
                print(f"[shape] {where}: stem ends with punctuation -> {stem!r}")
                problems += 1
            if "?" in stem or "Question:" in stem or "Answer:" in stem:
                print(f"[shape] {where}: stem still looks like a prompt -> {stem!r}")
                problems += 1
            if gold not in it["options"]:
                print(f"[shape] {where}: correct answer is not among the options")
                problems += 1

            leaked = (content_words(gold) & content_words(stem)) - content_words(q)
            leaked -= set().union(*(content_words(o) for o in others)) if others else set()
            if leaked:
                print(f"[leak]  {where}: {sorted(leaked)} is in the stem and the gold "
                      f"option only\n        stem: {stem}\n        gold: {gold}")
                problems += 1

            last = stem.rsplit(" ", 1)[-1].lower()
            if last in {"the", "a", "an"}:
                determiners.append((where, stem, it["options"]))

    if determiners:
        print(f"\n[determiner] {len(determiners)} stems end in a determiner. Each is "
              "only safe if all\n             four options take it. Read them:")
        for where, stem, opts in determiners:
            print(f"  {where}: ...{' '.join(stem.split()[-6:])} __")
            print(f"      {' | '.join(opts)}")

    total = sum(len(v) for v in built.values())
    print(f"{concept}: {total} questions, {problems} problem(s)")
    return problems


def anchor(text: str) -> str:
    return re.sub(r"[^a-z0-9 -]", "", text.lower()).replace(" ", "-")


def render(all_built: dict) -> str:
    out = [HEADER.rstrip("\n"), ""]
    w = out.append
    for concept in all_built:
        w(f"- [{concept}](#{anchor(concept)})")
    w("")
    w("The stem is what the model is given. The four options are scored as "
      "continuations of it, in the order below; at evaluation time they are "
      "shuffled per question with seed 42, exactly as in the multiple-choice "
      "run, so the printed order is not the order the model sees. `___` marks "
      "where the option is appended, with one leading space.")
    w("")
    w("---")
    w("")
    for concept, built in all_built.items():
        w(f"# {concept}")
        w("")
        for split, title in SPLIT_TITLES:
            w(f"## {concept}: {title}")
            w("")
            w(f"`{concept}` / `{split}`")
            w("")
            for n, it in enumerate(built[split], 1):
                w(f"**{n}.** {it['stem']} ___")
                w("")
                for opt in it["options"]:
                    w(f"- {opt}")
                w("")
                w(f"*Answer:* {it['correct_answer']}")
                w("")
                w(f"*Original:* {it['q']}")
                w("")
            w("---")
            w("")
    return "\n".join(out)


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--ember-data", help="EMBER repo data/ directory")
    ap.add_argument("--in-json", default="data/completion_questions.json",
                    help="fallback source when --ember-data is absent")
    ap.add_argument("--out-json", default="data/completion_questions.json")
    ap.add_argument("--out-md", default="COMPLETIONS.md")
    ap.add_argument("--concept", nargs="+", default=DEFAULT_CONCEPTS,
                    help="concepts to build; each needs its own stems_<slug>.py")
    ap.add_argument("--check", action="store_true", help="validate only, write nothing")
    ap.add_argument("--only", action="store_true",
                    help="drop concepts already in --out-json instead of keeping them")
    args = ap.parse_args()

    source = load_source(args.ember_data, args.in_json)
    all_built, problems = {}, 0
    for concept in args.concept:
        built = attach(source, concept)
        problems += check(built, concept)
        all_built[concept] = built
    if args.check:
        raise SystemExit(1 if problems else 0)
    if problems:
        raise SystemExit("refusing to write with unresolved problems")

    # Concepts already in the output file survive unless --only, so building one
    # topic at a time adds to the set instead of replacing it.
    out_path = Path(args.out_json)
    merged = {}
    if out_path.exists() and not args.only:
        merged.update(json.loads(out_path.read_text(encoding="utf-8")))
    merged.update(all_built)
    merged = {k: merged[k] for k in sorted(merged)}

    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(json.dumps(merged, indent=1, ensure_ascii=False) + "\n",
                        encoding="utf-8")
    text = render(merged)
    Path(args.out_md).write_text(text, encoding="utf-8")
    print(f"wrote {args.out_json} ({len(merged)} concept(s)) and {args.out_md}")


if __name__ == "__main__":
    main()
