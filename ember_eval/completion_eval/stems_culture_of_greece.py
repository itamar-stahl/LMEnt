"""Declarative-stem rewrites of EMBER's Culture of Greece questions.

Same rules as stems_pornography.py, which is the reference copy of them:

  1. Declarative prose, no question mark, no "Question:".
  2. All four options continue the stem grammatically.
  3. Written from the question, never from the answer key.
  4. Stop before a determiner unless all four options take it.
  5. Options, answer key, file order and shuffle seed unchanged.

Rule 4 costs nothing on "a"/"an" here and not one stem ends on either: Greek
answers are overwhelmingly proper nouns and article-less terms -- Rebetiko,
Ouzo, Bouzouki, Parthenon -- so the 19 determiner-final stems all end on "the"
and all 19 take whole option sets of the same shape.

EMBER repeats a question verbatim in this concept, and it is the only exact
duplicate in all 3,600 of its questions. QA_train #22 and #26 are both "What is
Katharevousa in the context of the Greek language?", with different option sets
whose gold answers paraphrase each other. The lookup key is a prefix of the
question, so no key of any length can separate them; both entries therefore
carry the same prefix and the same stem, which makes the pairing order a no-op.
build_completions.attach() needs its duplicate-aware branch for this concept and
for no other. See PROVENANCE.md.

Two deviations from the original wording:

  QA_test #41 "What public holiday in Greece commemorates the Dormition of the
      Holy Virgin?" is answered by four dates (August 15 / September 8 /
      December 25 / January 6), not by four holiday names, so the stem asks when
      rather than which: "...commemorating the Dormition of the Holy Virgin
      falls on". The question contradicts its own option set; this is the Shunga
      case with the premise pointing at the wrong part of speech.
  SimdomQA_train #36 "Which film festival is one of the most prestigious in
      modern cinema?" pluralises to "One of the most prestigious film festivals
      in modern cinema is the". A grammatical adaptation, not a content change,
      and the precedent is the Ancient Rome aqueducts item.

Six items are answerable from the question by word overlap alone -- QA_train #17
(Patras), QA_train #19 (Thessaloniki), QA_test #19 (Greek), SimdomQA_train #44
(Nazca), SimdomQA_test #2 (Roman), SimdomQA_test #24 (Islamic). All six are
inherited from EMBER's wording and none was introduced by the rewrite.
"""
