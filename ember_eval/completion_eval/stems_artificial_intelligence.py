"""Declarative-stem rewrites of EMBER's Artificial intelligence questions.

Same rules as stems_pornography.py, which is the reference copy of them:

  1. Declarative prose, no question mark, no "Question:".
  2. All four options continue the stem grammatically.
  3. Written from the question, never from the answer key.
  4. Stop before a determiner unless all four options take it.
  5. Options, answer key, file order and shuffle seed unchanged.

Rule 2 does most of the work here, because this concept has the widest spread of
option shapes in the set. Several items answer with whole clauses that open on a
capitalised "It" -- "It deleted thousands of user photos", "It mistakenly
identified ..." -- which no noun-phrase frame accepts, so those stems end on
"was that" and take the clause frame documented in stems_baseball.py. Others
answer with quantified adjuncts ("At least 2 hidden layers"), where the stem has
to stop on "when it has".

Rule 3 is tighter here than anywhere else, because the gold answers are often
built from the same words a natural stem would reach for and the distractors do
not supply them. "Artificial neural network" shares no content word with its
question or with any of its three distractors, so artificial, neural and network
are all gold-only and the stem has to name the referent generically. The same
happens with Operating System, Web Browser, Malware and Solid State Drive in the
similar-domain splits: in each case the question's own paraphrase is kept and the
gold's vocabulary stays out.

Abbreviation questions ("What does LSTM stand for") would otherwise yield
three-word stems, so they take a domain frame -- "In deep learning, the
abbreviation LSTM stands for". stems_baseball.py mixes framed and bare forms in
one file, so both are in the house style.

27 of the 200 stems end on a determiner and all 27 were read against their four
options.

No deviations from the original wording.
"""
